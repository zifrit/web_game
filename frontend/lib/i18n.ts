export type TranslationKey = keyof typeof dictionaries.en;

export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "ru" ? "ru" : "en";
}

export function readStoredLocale(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
}

export function writeStoredLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
}

export function translate(locale: Locale, key: TranslationKey, params: Params = {}) {
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

export function makeTranslator(locale: Locale) {
  return (key: TranslationKey, params?: Params) => translate(locale, key, params);
}

export function formatNumber(value: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "ru" ? "ru-RU" : "en-US").format(value);
}

export function splitCopper(value: number | undefined) {
  const copperTotal = Math.max(0, Math.floor(value ?? 0));
  return {
    gold: Math.floor(copperTotal / 10000),
    silver: Math.floor((copperTotal % 10000) / 100),
    copper: copperTotal % 100,
  };
}

function copperLabels(locale: Locale) {
  return locale === "ru"
    ? { gold: "з", silver: "с", copper: "м" }
    : { gold: "g", silver: "s", copper: "c" };
}

export function formatCopper(value: number | undefined, locale: Locale) {
  const parts = splitCopper(value);
  const labels = copperLabels(locale);

  return [
    `${formatNumber(parts.gold, locale)}${labels.gold}`,
    `${parts.silver}${labels.silver}`,
    `${parts.copper}${labels.copper}`,
  ].join(" ");
}

/** Компактная сумма: опускает нулевые разряды, "?" для пустого значения. */
export function formatCopperCompact(value: number | undefined | null, locale: Locale): string {
  if (value === undefined || value === null) return "?";
  const { gold, silver, copper } = splitCopper(value);
  const labels = copperLabels(locale);
  const parts: string[] = [];
  if (gold > 0) parts.push(`${gold}${labels.gold}`);
  if (silver > 0) parts.push(`${silver}${labels.silver}`);
  if (copper > 0 || parts.length === 0) parts.push(`${copper}${labels.copper}`);
  return parts.join(" ");
}

export function formatTime(secs: number) {
  const h = Math.floor(secs / 3600);
  const m = Math.floor((secs % 3600) / 60);
  const s = secs % 60;
  if (h > 0) return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
  return `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
}

export function formatDuration(seconds: number, locale: Locale) {
  const minutes = Math.floor(seconds / 60);
  const rest = seconds % 60;
  if (minutes <= 0) return `${rest}${locale === "ru" ? "с" : "s"}`;
  return `${minutes}${locale === "ru" ? "м" : "m"} ${rest.toString().padStart(2, "0")}${locale === "ru" ? "с" : "s"}`;
}

export function formatStatName(key: string, locale: Locale) {
  const statKey = `stats.${key}` as TranslationKey;
  return dictionaries[locale][statKey] ?? key.replaceAll("_", " ");
}
